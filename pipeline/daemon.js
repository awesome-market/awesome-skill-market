#!/usr/bin/env node
// daemon.js — foreground loop. Ctrl-C stops. One cycle = sync -> extract -> merge -> evidence -> issues -> build -> validate -> commit/push.
import { CFG, ROOT } from './lib/env.js';
import { log, sleep, git, gitDirty } from './lib/util.js';
import { sync } from './sync.js';
import { extract } from './extract.js';
import { merge } from './merge.js';
import { evidence } from './evidence.js';
import { issues } from './issues.js';
import { translateConflicts } from './translate.js';
import { poll } from './poll.js';
import { build } from './build.js';

const once = process.argv.includes('--once');
const skipLLM = process.argv.includes('--no-llm');

function commitAndPush() {
  if (!gitDirty(ROOT)) { log('git: nothing to commit'); return; }
  git(['add', '-A'], { cwd: ROOT });
  const msg = `pipeline: cycle ${new Date().toISOString()}\n\nGenerated by skill-fusion daemon.`;
  git(['commit', '-m', msg], { cwd: ROOT });
  try {
    git(['push'], { cwd: ROOT });
    log('git: pushed');
  } catch (e) {
    log('git: push failed (staying local):', e.message?.split('\n')[0]);
  }
}

async function cycle() {
  log('--- cycle start ---');
  const changed = await sync();

  if (changed.length || skipLLM) {
    const names = changed.length ? changed : undefined;
    await extract(names);
  } else {
    log('extract: no upstream changes');
  }

  if (!skipLLM) {
    await merge();
    await translateConflicts(); // backfill zh fields the judge missed
    await evidence();
    await issues();
    await poll(); // harvest a/b votes from issue comments
  } else {
    log('merge/evidence/issues skipped (--no-llm)');
    await poll(); // votes don't need the model
  }

  build();
  const { spawnSync } = await import('node:child_process');
  const v = spawnSync('node', ['pipeline/validate.js'], { cwd: ROOT, stdio: 'inherit' });
  if (v.status !== 0) log('validate: FAILED (leaving findings for review)');
  commitAndPush();
  log('--- cycle done ---');
}

async function main() {
  if (!CFG.model) log('warn: OMLX_MODEL unset');
  for (;;) {
    try {
      await cycle();
    } catch (e) {
      log(`cycle error: ${e.stack ?? e.message}`);
    }
    if (once) break;
    log(`sleeping ${CFG.intervalMin}m — Ctrl-C to stop`);
    await sleep(CFG.intervalMin * 60_000);
  }
}

await main();
