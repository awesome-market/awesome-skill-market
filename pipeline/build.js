#!/usr/bin/env node
// build.js — merged/rules.yml + decisions -> skill/SKILL.md + references/*.md + rules-manifest.yml
// --check: rebuild to temp, diff against committed skill/ (CI reproducibility gate)
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { DIRS, FILES, ROOT } from './lib/env.js';
import { log, readJSON, readYAML, writeYAML, listYAMLFiles, sha1 } from './lib/util.js';

const SCOPES = ['color', 'type', 'layout', 'motion', 'a11y', 'copy', 'imagery', 'code', 'process'];
const STATE = path.join(DIRS.merged, 'build-state.json');

function render(rules, version) {
  const out = new Map(); // relPath -> content

  const floor = rules.filter((r) => r.severity === 'floor');
  const reflex = rules.filter((r) => r.severity === 'reflex');
  const finish = rules.filter((r) => r.severity === 'finish');
  const guidance = rules.filter((r) => r.severity === 'guidance');

  const byScope = new Map(SCOPES.map((s) => [s, rules.filter((r) => r.scope?.includes(s))]));
  const refList = [...byScope.entries()].filter(([, v]) => v.length);

  let md = `---
name: design-fusion
description: "Merged anti-AI-slop design skill. Use when building, redesigning, reviewing, or auditing web/app UI. Distilled from multiple upstream design skills with human-arbitrated conflict resolution; covers aesthetic direction, hard floor rules, motion/a11y craft details."
version: "${version}"
---

# Design Fusion

Rules distilled from upstream design skills by the skill-fusion pipeline. **Do not edit this file** — change \`decisions/\` or upstream and rebuild.

## The Floor — never ship a violation

${floor.map((r) => `- ${r.rule}`).join('\n')}

## Reflex defaults — apply unless the brief says otherwise

${reflex.map((r) => `- ${r.rule}`).join('\n')}

## Finish — craft details, apply when polishing

${finish.map((r) => `- ${r.rule}`).join('\n')}

## Direction — guidance, not checkboxes

${guidance.map((r) => `- ${r.rule}`).join('\n')}

## References — load on demand for the scope you're working in

${refList.map(([s, v]) => `- \`references/${s}.md\` — ${v.length} rules on ${s}`).join('\n')}

## Lint

Mechanizable floor/reflex rules are encoded in \`lint/rules.json\` next to this file's source repo — run \`node lint/run.mjs <paths>\` for a deterministic pass before shipping.
`;
  out.set('SKILL.md', md);

  for (const [scope, list] of refList) {
    out.set(`references/${scope}.md`, `# ${scope}\n\n` + list.map((r) =>
      `- **(${r.severity})** ${r.rule}${r.decidedBy ? `  _[arbitrated: ${r.decidedBy}]_` : ''}`,
    ).join('\n') + '\n');
  }

  return out;
}

export function build({ check = false } = {}) {
  const doc = readYAML(FILES.mergedRules, { rules: [] });
  const rules = doc.rules ?? [];
  const decisions = listYAMLFiles(DIRS.decisions).map((f) => readYAML(f)).filter((d) => d?.status === 'active');

  const state = readJSON(STATE, { counter: 0, contentHash: '' });
  const probe = render(rules, '0.0.0');
  const probeHash = sha1([...probe.entries()].map(([k, v]) => k + v).join('\n'));
  const contentChanged = probeHash !== state.contentHash;
  const counter = contentChanged ? (state.counter ?? 0) + 1 : (state.counter ?? 0) || 1;
  const version = `0.${counter}.${decisions.length}`;

  const files = render(rules, version);

  if (check) {
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'skill-build-'));
    for (const [rel, content] of files) {
      const p = path.join(tmp, rel);
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.writeFileSync(p, content);
    }
    try {
      execFileSync('diff', ['-r', '--exclude=rules-manifest.yml', tmp, DIRS.skill], { stdio: 'pipe' });
      log('build --check: skill/ is reproducible');
      return true;
    } catch {
      console.error('build --check FAILED: skill/ is stale. Run `npm run build` and commit.');
      return false;
    } finally {
      fs.rmSync(tmp, { recursive: true, force: true });
    }
  }

  for (const f of fs.readdirSync(DIRS.skill).filter((f) => f !== 'lint')) {
    fs.rmSync(path.join(DIRS.skill, f), { recursive: true, force: true });
  }
  for (const [rel, content] of files) {
    const p = path.join(DIRS.skill, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
  writeYAML(path.join(DIRS.skill, 'rules-manifest.yml'), {
    version,
    built_at: new Date().toISOString(),
    counts: doc.counts,
    decisions: decisions.map((d) => ({ id: d.id, resolution: d.resolution, at: d.decided_at })),
    rules,
  });
  writeJSON(STATE, { counter, contentHash: probeHash });
  log(`build: skill/ v${version}, ${rules.length} rules, ${decisions.length} decisions${contentChanged ? '' : ' (no content change)'}`);
  return true;
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const ok = build({ check: process.argv.includes('--check') });
  process.exit(ok ? 0 : 1);
}
